// Regex cross-checks and registration-style inventory. Run: node research/wasm/survey/regex-counts.ts
import { readdirSync, statSync, readFileSync } from "fs";
import { join, relative } from "path";
const ROOT = join(import.meta.dirname, "../../..");
const walk = (d: string, o: string[] = []) => { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? (n !== "node_modules" && walk(p, o)) : /\.ts$/.test(n) && !/\.test\.ts$|testkit|\.d\.ts$/.test(n) && o.push(p); } return o; };
const files = walk(join(ROOT, "src"));
const pats: Record<string, RegExp> = {
  "method-signature keys  \"name(desc)ret\":": /^\s*(?:"|')(?:static )?[\w$<>]+\([^"'\n]*\)[^"'\n]*(?:"|')\s*:/gm,
  "rt.register({": /\brt\.register\(/g,
  "registerJnis(": /\bregisterJnis\(/g,
  "delegate( alias": /\bdelegate\(\s*"/g,
  "registerJni(": /\bregisterJni\(/g,
  "rt.intrinsic(": /\.intrinsic\(/g,
  "defineHost( (guest-callable libc/EGL/etc host fns)": /\bdefineHost\(/g,
  "def(n,\"Name\" JNIEnv table slots": /\bdef\(\d+,\s*"/g,
  "driven( generator natives": /\bdriven\(/g,
  "fieldGetters/fieldSetters/stubs/noops tables": /\b(fieldGetters|fieldSetters|stubs|noops)\(/g,
  "native class ctor with 'extends JObj' (+subclasses by name J*/Native*)": /\bclass \w+ extends (JObj|J[A-Z]\w*)\b/g,
  "spec.fields / serialization (Java-visible field → JS prop maps)": /\bfields:\s*[\[{]/g,
  "getDeclared/setDeclared/declaredField": /\b(getDeclared|setDeclared|declaredField)\(/g,
  "literal 'f$' mangled field names": /["'`]f\$/g,
  "literal 'm$' mangled method names": /["'`]m\$/g,
  "rt.natives.get( patching": /rt\.natives\.get\(/g,
  "jniResolver / RegisterNatives": /jniResolver|RegisterNatives/g,
  "$t tag use": /\.\$t\b/g,
  "csText(": /\bcsText\(/g,
  "TYPE_MARK": /TYPE_MARK/g,
  "generated registration (generated/GENERATED comment)": /generated by|GENERATED/g,
};
const dirs: [string, (r: string) => boolean][] = [
  ["jvm/natives", (r) => r.startsWith("src/jvm/natives/")], ["jvm/other", (r) => r.startsWith("src/jvm/") && !r.startsWith("src/jvm/natives/")],
  ["android", (r) => r.startsWith("src/android/")], ["native", (r) => r.startsWith("src/native/")], ["shell", (r) => r.startsWith("src/shell/")], ["src/*", (r) => r.split("/").length === 2],
];
const src = files.map((f) => [relative(ROOT, f), readFileSync(f, "utf8")] as const);
for (const [name, re] of Object.entries(pats)) {
  const row = dirs.map(([d, pr]) => `${d}=${src.filter(([r]) => pr(r)).reduce((a, [, t]) => a + (t.match(re)?.length ?? 0), 0)}`);
  const tot = src.reduce((a, [, t]) => a + (t.match(re)?.length ?? 0), 0);
  console.log(String(tot).padStart(6), name, "|", row.join(" "));
}
