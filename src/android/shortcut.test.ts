import { expect, test } from "bun:test";
import "../natives";
import { JObj, rt } from "../jvm/runtime";
import { newObj, vcall } from "../jvm/natives/jlang";
import { newArrayList } from "../jvm/natives/jutil";
import { appHost } from "./apphost";

rt.register({ name: "test/ShortcutContext", ctor: class extends JObj {}, methods: { "getPackageName()Ljava/lang/String;": () => appHost?.pkg ?? "" } });

test("dynamic shortcuts retain independent intent and metadata snapshots", async () => {
  const builder = await newObj("android/content/pm/ShortcutInfo$Builder", "(Landroid/content/Context;Ljava/lang/String;)V", await newObj("test/ShortcutContext"), "open-board");
  const descriptor = "Landroid/content/pm/ShortcutInfo$Builder;";
  const intent = await newObj("android/content/Intent", "(Ljava/lang/String;)V", "android.intent.action.VIEW");
  intent.pkg = "target.package"; intent.typeStr = "text/plain"; intent.categories.add("test.category"); intent.extras.map.set("board", "original");
  await vcall(builder, "setShortLabel", "(Ljava/lang/CharSequence;)" + descriptor, "Open board");
  await vcall(builder, "setIntent", "(Landroid/content/Intent;)" + descriptor, intent);
  await vcall(builder, "setExcludedFromSurfaces", "(I)" + descriptor, 1);
  const shortcut = await vcall(builder, "build", "()Landroid/content/pm/ShortcutInfo;");
  intent.action = "modified"; intent.categories.clear(); intent.extras.map.set("board", "modified");
  await vcall(builder, "setShortLabel", "(Ljava/lang/CharSequence;)" + descriptor, "Changed");
  expect(await vcall(shortcut, "getShortLabel", "()Ljava/lang/CharSequence;")).toBe("Open board");
  const copy = await vcall(shortcut, "getIntent", "()Landroid/content/Intent;");
  expect(copy.action).toBe("android.intent.action.VIEW");
  expect(copy.pkg).toBe("target.package");
  expect(copy.typeStr).toBe("text/plain");
  expect([...copy.categories]).toEqual(["test.category"]);
  expect(copy.extras.map.get("board")).toBe("original");
  expect(await vcall(shortcut, "isExcludedFromSurfaces", "(I)Z", 1)).toBe(1);
  const manager = await newObj("android/content/pm/ShortcutManager");
  const list = newArrayList(); list.a = [shortcut];
  expect(await vcall(manager, "setDynamicShortcuts", "(Ljava/util/List;)Z", list)).toBe(1);
  expect(await vcall(shortcut, "isDynamic", "()Z")).toBe(0);
  const published = (await vcall(manager, "getDynamicShortcuts", "()Ljava/util/List;")).a;
  expect(published.length).toBe(1);
  expect(await vcall(published[0], "isDynamic", "()Z")).toBe(1);
  published[0].shortLabel = "mutated";
  expect((await vcall(manager, "getDynamicShortcuts", "()Ljava/util/List;")).a[0].shortLabel).toBe("Open board");
  expect(await vcall(manager, "isRequestPinShortcutSupported", "()Z")).toBe(0);
  await vcall(manager, "removeAllDynamicShortcuts", "()V");
  expect((await vcall(manager, "getDynamicShortcuts", "()Ljava/util/List;")).a).toEqual([]);
});
