import { afterAll, beforeAll, expect, test } from "bun:test";
import { JThread } from "../jvm/natives/jlang";
import { Cpu, setA64 } from "./cpu";
import { lookupHost } from "./host";
import { libcInit } from "./libc";
import { mem } from "./mem";

const host = (name: string) => lookupHost(name, "libc.so")!;
beforeAll(() => { setA64(true); libcInit(); });
afterAll(() => setA64(false));

test("epoll watches socket readiness with edge and one-shot rearming", async () => {
  const cpu = new Cpu(new JThread(), "epoll socket test");
  const socket = await cpu.call(host("socket"), [2, 2 | 0x800, 0]);
  const sender = await cpu.call(host("socket"), [2, 2, 0]);
  const address = mem.hostAlloc(16), event = mem.hostAlloc(16), output = mem.hostAlloc(16), byte = mem.hostAlloc(1);
  mem.st16(address, 2); mem.u8[address + 2] = 178; mem.u8[address + 3] = 231;
  mem.u8.set([127, 0, 0, 1], address + 4);
  expect(await cpu.call(host("bind"), [socket, address, 16])).toBe(0);
  const epoll = await cpu.call(host("epoll_create1"), [0]);
  mem.st32(event, 0x80000001); mem.st64(event + 8, 0x123456789n);
  expect(await cpu.call(host("epoll_ctl"), [epoll, 1, socket, event])).toBe(0);
  expect(await cpu.call(host("epoll_ctl"), [epoll, 1, socket, event])).toBe(-1);
  expect(mem.ld32(cpu.errnoAddr)).toBe(17);
  const send = () => cpu.call(host("sendto"), [sender, byte, 1, 0, address, 16]);
  const poll = () => cpu.call(host("epoll_wait"), [epoll, output, 1, 0]);
  await send();
  expect(await poll()).toBe(1);
  expect(mem.ld32(output)).toBe(1);
  expect(mem.ld64(output + 8)).toBe(0x123456789n);
  expect(await poll()).toBe(0);
  await cpu.call(host("recvfrom"), [socket, byte, 1, 0, 0, 0]);
  await send();
  expect(await poll()).toBe(1);
  mem.st32(event, 0x40000001);
  expect(await cpu.call(host("epoll_ctl"), [epoll, 3, socket, event])).toBe(0);
  expect(await poll()).toBe(1);
  expect(await poll()).toBe(0);
  expect(await cpu.call(host("epoll_ctl"), [epoll, 3, socket, event])).toBe(0);
  expect(await poll()).toBe(1);
  mem.st32(event, 4);
  await cpu.call(host("epoll_ctl"), [epoll, 3, socket, event]);
  expect(await poll()).toBe(1);
  expect(mem.ld32(output)).toBe(4);
  await cpu.call(host("recvfrom"), [socket, byte, 1, 0, 0, 0]);
  mem.st32(event, 0x80000001);
  await cpu.call(host("epoll_ctl"), [epoll, 3, socket, event]);
  const waiting = cpu.call(host("epoll_wait"), [epoll, output, 1, 1000]);
  const other = new Cpu(new JThread(), "epoll sender test");
  await other.call(host("sendto"), [sender, byte, 1, 0, address, 16]);
  expect(await waiting).toBe(1);
  for (const fd of [epoll, socket, sender]) await cpu.call(host("close"), [fd]);
});

test("epoll wakes for timer expiration and descriptors added during a wait", async () => {
  const cpu = new Cpu(new JThread(), "epoll wait test"), other = new Cpu(new JThread(), "epoll ctl test");
  const epoll = await cpu.call(host("epoll_create1"), [0]);
  const timer = await cpu.call(host("timerfd_create"), [1, 0x800]);
  const event = mem.hostAlloc(16), output = mem.hostAlloc(32), spec = mem.hostAlloc(32);
  mem.st32(event, 1); mem.st64(event + 8, 0x987654321n);
  const waiting = cpu.call(host("epoll_wait"), [epoll, output, 2, 1000]);
  expect(await other.call(host("epoll_ctl"), [epoll, 1, timer, event])).toBe(0);
  mem.st64(spec + 24, 20_000_000n);
  expect(await other.call(host("timerfd_settime"), [timer, 0, spec, 0])).toBe(0);
  expect(await waiting).toBe(1);
  expect(mem.ld64(output + 8)).toBe(0x987654321n);
  await cpu.call(host("close"), [epoll]);
  await cpu.call(host("close"), [timer]);
});
