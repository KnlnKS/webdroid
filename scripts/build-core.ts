// Build the wasm core from src/native/core/*.zig into src/native/core.wasm.ts (ReleaseFast,
// shipped) and core.safe.wasm.ts (ReleaseSafe: undefined behaviour panics, which the tests run
// against). Production ships the ReleaseFast binary; other runtimes use generated base64 modules.
// The outputs are not committed: `ensureCore` rebuilds them when a Zig source
// is newer, and bunfig.toml preloads it before every bun entry point.
//
//   bun run build:core          rebuild when stale
//   bun run build:core --force  rebuild
import { $ } from "bun";
import { readdirSync, statSync } from "node:fs";
import { rename, rm } from "node:fs/promises";

const FEATURES = "generic+simd128+bulk_memory+sign_ext+nontrapping_fptoint+mutable_globals";
const dir = "src/native";
const src = `${dir}/core`;
const OUT = [["ReleaseFast", "core.wasm"], ["ReleaseSafe", "core.safe.wasm"]] as const;
const mtime = (p: string) => { try { return statSync(p).mtimeMs; } catch { return -1; } };

function stale(): boolean {
  const newest = Math.max(mtime("scripts/build-core.ts"), ...readdirSync(src).map((f) => mtime(`${src}/${f}`)));
  return OUT.some(([, name]) => mtime(`${dir}/${name}.ts`) < newest) || mtime(`${dir}/native-core.wasm`) < newest;
}
async function build(): Promise<void> {
  await Promise.all(OUT.map(async ([mode, name]) => {
    const bin = `${dir}/${name}`;
    await $`zig build-exe ${src}/core.zig -target wasm32-freestanding -O ${mode} -mcpu=${FEATURES} -fno-entry -rdynamic --import-memory --max-memory=4294901760 --import-table --global-base=65536 --stack 262144 --export=__heap_base -fstrip -femit-bin=${bin}`;
    const bytes = new Uint8Array(await Bun.file(bin).arrayBuffer());
    if (mode === "ReleaseFast") await rename(bin, `${dir}/native-core.wasm`);
    else await rm(bin);
    await rm(`${bin}.o`, { force: true });
    await Bun.write(`${bin}.ts`, `// generated by scripts/build-core.ts (${mode}, ${bytes.length} bytes); do not edit\nexport default "${bytes.toBase64()}";\n`);
    console.log(`${name}: ${bytes.length} bytes`);
  }));
}
export async function ensureCore(): Promise<void> {
  if (stale()) await build();
}
if (import.meta.main) await (process.argv.includes("--force") ? build() : ensureCore());
