import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { writeWhole } from "./generated.ts";

const url = "https://raw.githubusercontent.com/aosp-mirror/platform_system_core/android-15.0.0_r1/libcutils/include/private/android_filesystem_config.h";
const response = await fetch(url);
if (!response.ok) throw new Error(`${response.status}: ${url}`);
const source = await response.text(), ids: Record<string, number> = {};
for (const [, name, number] of source.matchAll(/^#define AID_(\w+)\s+(\d+)/gm)) {
  if (/^(UNUSED\d|APP|USER)/.test(name!) || /_(START|END)$/.test(name!)) continue;
  const friendly = name!.toLowerCase().replace(/^media_(drm|ex|codec)$/, "media$1");
  ids[friendly] = Number(number);
}
const hash = createHash("sha256").update(source).digest("hex");
writeWhole(fileURLToPath(new URL("../src/android/identity-data.ts", import.meta.url)),
  `// Generated by pnpm ts scripts/gen-android-ids.ts from ${url}\n// SHA-256: ${hash}\nexport const androidIds: Readonly<Record<string, number>> = ${JSON.stringify(ids, null, 2)};\n`);
