// Bundle the programs a WebView's renderer runs (src/shell/webpage: the page script, the renderer
// bootstrap and the proxy worker) into src/shell/webpage.gen.ts, as strings the servers and the
// provider serve. Not committed: `ensureWebPages` rebuilds it when a source is newer, and
// bunfig.toml preloads it before every bun entry point.
import { readdirSync, renameSync, statSync, writeFileSync } from "node:fs";

const dir = "src/shell/webpage", out = "src/shell/webpage.gen.ts";
const mtime = (p: string) => { try { return statSync(p).mtimeMs; } catch { return -1; } };

/** `entry` as one classic script, safe inside a <script> element */
async function bundle(entry: string, define?: Record<string, string>): Promise<string> {
  const built = await Bun.build({ entrypoints: [`${dir}/${entry}`], format: "iife", target: "browser", define, minify: { whitespace: true, syntax: true } });
  if (!built.success) throw new AggregateError(built.logs, `${entry} failed to bundle`);
  return (await built.outputs[0].text()).replace(/<\/(script)/gi, "<\\/$1");
}

export async function ensureWebPages(): Promise<void> {
  const newest = Math.max(mtime("scripts/build-web.ts"), ...readdirSync(dir).map((f) => mtime(`${dir}/${f}`)));
  if (mtime(out) >= newest) return;
  const inject = `<script>${await bundle("inject.ts")}</script>`;
  const frame = `<!doctype html><meta charset="utf-8"><script>${await bundle("renderer.ts", { WEB_INJECT: JSON.stringify(inject) })}</script>`;
  const worker = await bundle("worker.ts");
  // concurrent entry points may build at once: each writes whole, then takes the name
  const temp = `${out}.${process.pid}`;
  writeFileSync(temp, `// generated by scripts/build-web.ts from ${dir}; do not edit\n`
    + `export const WEB_INJECT = ${JSON.stringify(inject)};\nexport const WEB_FRAME = ${JSON.stringify(frame)};\nexport const WEB_PROXY_WORKER = ${JSON.stringify(worker)};\n`);
  renameSync(temp, out);
}
if (import.meta.main) await ensureWebPages();
