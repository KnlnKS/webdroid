// The generated modules src imports, none committed; each is rebuilt when a source is newer.
//   core    src/native/core/*.zig as core.wasm.ts (ReleaseFast, which ships as native-core.wasm) and core.safe.wasm.ts
//           (ReleaseSafe: undefined behaviour panics, which the tests run against), and core-abi.gen.ts: abi.zig's address
//           map and libc.zig's function table
//   pages   the programs a WebView's renderer runs (src/shell/webpage) as strings in src/shell/webpage.gen.ts
//   sql.js  vendor/sql.js/dist, as rebuild.sh builds it with its patch
//   zlib    zlib's pinned release, downloaded once into ~/.cache/webdroid rather than vendored, as src/zlib.wasm.ts with
//           the functions src/zlib.ts's Exports names
//   node scripts/generated.ts [--force]
import { execFile, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { cli } from "./args.ts";

const run = promisify(execFile);
const mtime = (p: string) => { try { return statSync(p).mtimeMs; } catch { return -1; } };
/** whether an output is older than this script or an input */
const older = (outs: string[], inputs: string[]) => {
  const newest = Math.max(mtime(import.meta.filename), ...inputs.map(mtime));
  return outs.some((p) => mtime(p) < newest);
};
const stale = (dir: string, outs: string[]) => older(outs, readdirSync(dir).map((f) => `${dir}/${f}`));
/** `data` at `path` all at once: concurrent entry points may build at once, and a reader never sees part of it */
export function writeWhole(path: string, data: string | Uint8Array): void {
  const temporary = `${path}.${crypto.randomUUID()}.tmp`;
  writeFileSync(temporary, data);
  renameSync(temporary, path);
}

const NATIVE = "src/native", CORE = `${NATIVE}/core`, ABI = `${NATIVE}/core-abi.gen.ts`;
const FEATURES = "generic+simd128+bulk_memory+sign_ext+nontrapping_fptoint+mutable_globals+atomics";
const MODES = [["ReleaseFast", "core.wasm"], ["ReleaseSafe", "core.safe.wasm"]] as const;

/** abi.zig's and libc.zig's TLS_ constants are integer expressions JS evaluates alike; libc.zig numbers its functions from 1 */
function writeAbi(): void {
  const abi = readFileSync(`${CORE}/abi.zig`, "utf8"), libc = readFileSync(`${CORE}/libc.zig`, "utf8");
  const consts = [...abi.matchAll(/^pub const (\w+)(?:: u32)? = ([^;]+);$/gm)].map(([, name, value]) => `export const ${name} = ${value};`);
  const fns = libc.match(/pub const Fn = enum\(u8\) \{\s*none = 0,([^}]*)\}/)![1].split(",").map((f) => f.trim()).filter(Boolean);
  writeWhole(ABI, `// generated by scripts/generated.ts from src/native/core/abi.zig and libc.zig; do not edit\n${consts.join("\n")}
${[...libc.matchAll(/^pub const (TLS_\w+) = ([^;]+);$/gm)].map(([, name, value]) => `export const ${name} = ${value};`).join("\n")}
export const LIBC_FNS = ${JSON.stringify(fns)};\n`);
}
async function buildCore(): Promise<void> {
  writeAbi();
  await Promise.all(MODES.map(async ([mode, name]) => {
    const bin = `${NATIVE}/${process.pid}-${name}`;
    // Shared memory with thread-local lanes: each instance of a process's core (core.ts, lanes.ts) keeps its own stack and TLS,
    // and the passive data segments initialize the memory once, for the first.
    await run("zig", ["build-exe", `${CORE}/core.zig`, "-target", "wasm32-freestanding", "-O", mode, `-mcpu=${FEATURES}`, "-fno-single-threaded", "-fno-entry", "-rdynamic",
      "--import-memory", "--shared-memory", "--max-memory=4294901760", "--import-table", "--global-base=65536", "--stack", "262144", "--export=__heap_base",
      "--export=__stack_pointer", "--export=__wasm_init_tls", "--export=__tls_size", "--export=__tls_align", "-fstrip", `-femit-bin=${bin}`]);
    const bytes = new Uint8Array(readFileSync(bin));
    if (mode === "ReleaseFast") renameSync(bin, `${NATIVE}/native-core.wasm`);
    else rmSync(bin);
    rmSync(`${bin}.o`, { force: true });
    writeWhole(`${NATIVE}/${name}.ts`, `// generated by scripts/generated.ts (${mode}, ${bytes.length} bytes); do not edit\nexport default "${Buffer.from(bytes).toString("base64")}";\n`);
    console.log(`${name}: ${bytes.length} bytes`);
  }));
}

const PAGES = "src/shell/webpage", PAGES_OUT = "src/shell/webpage.gen.ts";
/** `entry` as one classic script, safe inside a <script> element */
const pageScript = async (entry: string, define?: Record<string, string>) =>
  (await (await import("./bundle.ts")).bundle(`${PAGES}/${entry}`, { format: "iife", minify: "syntax", define })).replace(/<\/(script)/gi, "<\\/$1");
async function buildPages(): Promise<void> {
  const inject = `<script>${await pageScript("inject.ts")}</script>`;
  const frame = `<!doctype html><meta charset="utf-8"><script>${await pageScript("renderer.ts", { WEB_INJECT: JSON.stringify(inject) })}</script>`;
  writeWhole(PAGES_OUT, `// generated by scripts/generated.ts from ${PAGES}; do not edit\n`
    + `export const WEB_INJECT = ${JSON.stringify(inject)};\nexport const WEB_FRAME = ${JSON.stringify(frame)};\nexport const WEB_PROXY_WORKER = ${JSON.stringify(await pageScript("worker.ts"))};\n`);
}

const SQLJS = "vendor/sql.js";
/** rebuild.sh swaps dist/ in whole with the patch it applied, so a matching copy means a complete build */
const sqlJsBuilt = () => existsSync(`${SQLJS}/dist/sqljs.patch`) && readFileSync(`${SQLJS}/dist/sqljs.patch`, "utf8") === readFileSync(`${SQLJS}/sqljs.patch`, "utf8");
const buildSqlJs = () => new Promise<void>((resolve, reject) => spawn("sh", [`${SQLJS}/rebuild.sh`], { stdio: ["ignore", "inherit", "inherit"] })
  .on("error", reject).on("exit", (code) => code ? reject(new Error("vendor/sql.js/rebuild.sh failed")) : resolve()));

const ZLIB = { version: "1.3.1", sha256: "9a93b2b7dfdac77ceba5a558a580e74667dd6fede4585b91eefb60f03b72df23", src: "src/zlib.ts", out: "src/zlib.wasm.ts" };
/** the release's sources, fetched once */
async function zlibSources(): Promise<string> {
  const dir = join(homedir(), ".cache/webdroid", `zlib-${ZLIB.version}`);
  if (existsSync(`${dir}/zlib.h`)) return dir;
  const archive = Buffer.from(await (await fetch(`https://github.com/madler/zlib/releases/download/v${ZLIB.version}/zlib-${ZLIB.version}.tar.gz`)).arrayBuffer());
  if (createHash("sha256").update(archive).digest("hex") !== ZLIB.sha256) throw new Error(`zlib ${ZLIB.version}: digest mismatch`);
  const work = mkdtempSync(`${dir}.`);
  writeFileSync(`${work}/src.tar.gz`, archive);
  await run("tar", ["xzf", `${work}/src.tar.gz`, "-C", work, "--strip-components=1"]);
  // a concurrent build may have put its copy in place first
  try { renameSync(work, dir); } catch (e) { if (!existsSync(`${dir}/zlib.h`)) throw e; rmSync(work, { recursive: true }); }
  return dir;
}
async function buildZlib(): Promise<void> {
  const dir = await zlibSources(), bin = `${NATIVE}/${process.pid}-zlib.wasm`;
  const exports = [...readFileSync(ZLIB.src, "utf8").match(/^interface Exports \{([^}]*)\}/m)![1].matchAll(/^\s+(\w+)\(/gm)].map(([, name]) => name);
  await run("zig", ["build-exe", ...["adler32", "crc32", "deflate", "inflate", "inffast", "inftrees", "trees", "zutil"].map((f) => `${dir}/${f}.c`),
    "-target", "wasm32-wasi", "-lc", "-O", "ReleaseFast", `-mcpu=${FEATURES}`, "-fno-entry", "-mexec-model=reactor", "--stack", "65536",
    ...exports.map((e) => `--export=${e}`), `-I${dir}`, "-fstrip", `-femit-bin=${bin}`]);
  const bytes = readFileSync(bin);
  rmSync(bin); rmSync(`${bin}.o`, { force: true });
  // src/zlib.ts instantiates it with no imports
  const imports = WebAssembly.Module.imports(new WebAssembly.Module(bytes));
  if (imports.length) throw new Error(`zlib.wasm imports ${imports.map((i) => `${i.module}.${i.name}`).join(", ")}`);
  writeWhole(ZLIB.out, `// generated by scripts/generated.ts (zlib ${ZLIB.version}, ${bytes.length} bytes); do not edit\nexport default "${bytes.toString("base64")}";\n`);
  console.log(`zlib.wasm: ${bytes.length} bytes`);
}

export async function ensureGenerated(force = false): Promise<void> {
  await Promise.all([
    (force || older([ZLIB.out], [ZLIB.src])) && buildZlib(),
    (force || stale(CORE, [...MODES.map(([, name]) => `${NATIVE}/${name}.ts`), `${NATIVE}/native-core.wasm`, ABI])) && buildCore(),
    (force || stale(PAGES, [PAGES_OUT])) && buildPages(),
    (force || !sqlJsBuilt()) && buildSqlJs(),
  ]);
}
if (import.meta.main) {
  const { values } = cli("node scripts/generated.ts [--force]", { force: { type: "boolean" } });
  await ensureGenerated(!!values.force);
}
