// The generated modules src imports, none committed; each is rebuilt when a source is newer.
//   core    src/native/core/*.zig as core.wasm.ts (ReleaseFast, which ships as native-core.wasm) and core.safe.wasm.ts
//           (ReleaseSafe: undefined behaviour panics, which the tests run against), and core-abi.gen.ts: abi.zig's address
//           map and libc.zig's function table
//   pages   the programs a WebView's renderer runs (src/shell/webpage) as strings in src/shell/webpage.gen.ts
//   sql.js  vendor/sql.js/dist, as rebuild.sh builds it with its patch
//   node scripts/generated.ts [--force] [--pages]
import { execFile, spawn } from "node:child_process";
import { existsSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { promisify } from "node:util";
import { cli } from "./args.ts";

const run = promisify(execFile);
const mtime = (p: string) => { try { return statSync(p).mtimeMs; } catch { return -1; } };
/** whether an output is older than this script or a file of `dir` */
const stale = (dir: string, outs: string[]) => {
  const newest = Math.max(mtime(import.meta.filename), ...readdirSync(dir).map((f) => mtime(`${dir}/${f}`)));
  return outs.some((p) => mtime(p) < newest);
};
/** `data` at `path` all at once: concurrent entry points may build at once, and a reader never sees part of it */
export function writeWhole(path: string, data: string | Uint8Array): void {
  const temporary = `${path}.${crypto.randomUUID()}.tmp`;
  writeFileSync(temporary, data);
  renameSync(temporary, path);
}

const NATIVE = "src/native", CORE = `${NATIVE}/core`, ABI = `${NATIVE}/core-abi.gen.ts`;
const FEATURES = "generic+simd128+bulk_memory+sign_ext+nontrapping_fptoint+mutable_globals";
const MODES = [["ReleaseFast", "core.wasm"], ["ReleaseSafe", "core.safe.wasm"]] as const;

/** abi.zig's constants are integer expressions JS evaluates alike; libc.zig numbers its functions from 1 */
function writeAbi(): void {
  const abi = readFileSync(`${CORE}/abi.zig`, "utf8"), libc = readFileSync(`${CORE}/libc.zig`, "utf8");
  const consts = [...abi.matchAll(/^pub const (\w+)(?:: u32)? = ([^;]+);$/gm)].map(([, name, value]) => `export const ${name} = ${value};`);
  const fns = libc.match(/pub const Fn = enum\(u8\) \{\s*none = 0,([^}]*)\}/)![1].split(",").map((f) => f.trim()).filter(Boolean);
  writeWhole(ABI, `// generated by scripts/generated.ts from src/native/core/abi.zig and libc.zig; do not edit\n${consts.join("\n")}
export const TLS_KEYS = ${libc.match(/pub const TLS_KEYS = (\d+);/)![1]};
export const LIBC_FNS = ${JSON.stringify(fns)};\n`);
}
async function buildCore(): Promise<void> {
  writeAbi();
  await Promise.all(MODES.map(async ([mode, name]) => {
    const bin = `${NATIVE}/${process.pid}-${name}`;
    await run("zig", ["build-exe", `${CORE}/core.zig`, "-target", "wasm32-freestanding", "-O", mode, `-mcpu=${FEATURES}`, "-fno-entry", "-rdynamic",
      "--import-memory", "--max-memory=4294901760", "--import-table", "--global-base=65536", "--stack", "262144", "--export=__heap_base", "-fstrip", `-femit-bin=${bin}`]);
    const bytes = new Uint8Array(readFileSync(bin));
    if (mode === "ReleaseFast") renameSync(bin, `${NATIVE}/native-core.wasm`);
    else rmSync(bin);
    rmSync(`${bin}.o`, { force: true });
    writeWhole(`${NATIVE}/${name}.ts`, `// generated by scripts/generated.ts (${mode}, ${bytes.length} bytes); do not edit\nexport default "${Buffer.from(bytes).toString("base64")}";\n`);
    console.log(`${name}: ${bytes.length} bytes`);
  }));
}

const PAGES = "src/shell/webpage", PAGES_OUT = "src/shell/webpage.gen.ts";
/** `entry` as one classic script, safe inside a <script> element */
const pageScript = async (entry: string, define?: Record<string, string>) =>
  (await (await import("./bundle.ts")).bundle(`${PAGES}/${entry}`, { format: "iife", minify: "syntax", define })).replace(/<\/(script)/gi, "<\\/$1");
async function buildPages(): Promise<void> {
  const inject = `<script>${await pageScript("inject.ts")}</script>`;
  const frame = `<!doctype html><meta charset="utf-8"><script>${await pageScript("renderer.ts", { WEB_INJECT: JSON.stringify(inject) })}</script>`;
  writeWhole(PAGES_OUT, `// generated by scripts/generated.ts from ${PAGES}; do not edit\n`
    + `export const WEB_INJECT = ${JSON.stringify(inject)};\nexport const WEB_FRAME = ${JSON.stringify(frame)};\nexport const WEB_PROXY_WORKER = ${JSON.stringify(await pageScript("worker.ts"))};\n`);
}

const SQLJS = "vendor/sql.js";
/** rebuild.sh swaps dist/ in whole with the patch it applied, so a matching copy means a complete build */
const sqlJsBuilt = () => existsSync(`${SQLJS}/dist/sqljs.patch`) && readFileSync(`${SQLJS}/dist/sqljs.patch`, "utf8") === readFileSync(`${SQLJS}/sqljs.patch`, "utf8");
const buildSqlJs = () => new Promise<void>((resolve, reject) => spawn("sh", [`${SQLJS}/rebuild.sh`], { stdio: ["ignore", "inherit", "inherit"] })
  .on("error", reject).on("exit", (code) => code ? reject(new Error("vendor/sql.js/rebuild.sh failed")) : resolve()));

const ensurePages = async (force: boolean) => { if (force || stale(PAGES, [PAGES_OUT])) await buildPages(); };

export async function ensureGenerated(force = false): Promise<void> {
  await Promise.all([
    (force || stale(CORE, [...MODES.map(([, name]) => `${NATIVE}/${name}.ts`), `${NATIVE}/native-core.wasm`, ABI])) && buildCore(),
    ensurePages(force),
    (force || !sqlJsBuilt()) && buildSqlJs(),
  ]);
}
if (import.meta.main) {
  const { values } = cli("node scripts/generated.ts [--force] [--pages]", { force: { type: "boolean" }, pages: { type: "boolean" } });
  await (values.pages ? ensurePages : ensureGenerated)(!!values.force);
}
