import { readFileSync } from "node:fs";
import { writeWhole } from "./generated.ts";
import { openInstall } from "../src/shell/install.ts";
import type { XmlNode } from "../src/android/axml.ts";

type Zip = Record<string, Uint8Array>;

/** an apk or a split install, as the one merged tree the shell boots — entries materialise on
 *  read, so there is nothing for a caller to filter down to */
export function openApk(path: string): Zip {
  return openInstall(new Uint8Array(readFileSync(path))).zip;
}

export function dumpXml(n: XmlNode, maxDepth = Infinity, depth = 0, out: string[] = []): string[] {
  const attrs = n.attrs.map((a) => `${a.name}=${a.str != null ? JSON.stringify(a.str) : "0x" + (a.data >>> 0).toString(16)}`).join(" ");
  out.push("  ".repeat(depth) + `<${n.name} ${attrs}>`);
  if (depth < maxDepth) for (const c of n.children) dumpXml(c, maxDepth, depth + 1, out);
  return out;
}
/** a source file gen-framework generates: its comment, which `header` continues, then `decls`; the
 *  log line names it with `summary` */
export function writeGenerated(file: string, header: string, decls: string, summary: string): void {
  writeWhole(file, `Generated by pnpm gen-framework${header}`.split("\n").map((line) => `// ${line}\n`).join("") + decls);
  console.log(`  ${file} ${summary}`);
}
/** `export const name: type = {` with a line per entry, its key and value as given */
export const constObject = (name: string, type: string, entries: (readonly [string, string | number])[]): string =>
  `export const ${name}: ${type} = {\n${entries.map(([k, v]) => `  ${k}: ${v},\n`).join("")}};\n`;
