const url = "https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt";
const source = process.argv[2] ? await Bun.file(process.argv[2]).text() : await (await fetch(url)).text();
const classes = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"];
const values = new Int8Array(0x110000).fill(-1);
let start = 0;
for (const line of source.trim().split("\n")) {
  const fields = line.split(";"), cp = parseInt(fields[0], 16), kind = classes.indexOf(fields[4]);
  if (!Number.isInteger(cp) || kind < 0) throw new Error("invalid UnicodeData row");
  if (fields[1].endsWith(", First>")) start = cp;
  else if (fields[1].endsWith(", Last>")) values.fill(kind, start, cp + 1);
  else values[cp] = kind;
}
const ranges: number[] = [];
for (let cp = 0; cp < values.length; cp++) if (values[cp] !== values[cp + 1]) ranges.push((cp << 5) | (values[cp] + 1));
const rows = Array.from({ length: Math.ceil(ranges.length / 16) }, (_, i) => "  " + ranges.slice(i * 16, i * 16 + 16).join(", ") + ",");
await Bun.write(new URL("../src/jvm/bidi-data.ts", import.meta.url), `// Generated by scripts/gen-bidi.ts from ${url}\n// Each entry packs a range's inclusive end and Java directionality + 1.\nexport const bidiRanges = new Uint32Array([\n${rows.join("\n")}\n]);\n`);
console.log(`${ranges.length} Unicode directionality ranges`);
