import { BYTECODE } from "../src/jvm/provenance";
BYTECODE.push("android/util/Patterns");
const { rt } = await import("../src/jvm/runtime");
const { mangleStaticField } = await import("../src/jvm/abi");
const { vcall } = await import("../src/jvm/natives/jlang");
const { loadJarDexes } = await import("./lib");
await import("../src/natives");
const jar = "vendor/aosp/framework.jar";
await loadJarDexes(jar);
const cls = rt.link("android/util/Patterns");
await rt.initClass(cls);
const patterns: Record<string, string> = {};
for (const name of ["WEB_URL", "EMAIL_ADDRESS", "IP_ADDRESS"]) {
  const pattern = Reflect.get(cls.ctor, mangleStaticField(name));
  const source = await vcall(pattern, "pattern", "()Ljava/lang/String;");
  if (typeof source !== "string") throw new Error(`Invalid Patterns.${name}`);
  patterns[name] = source;
}
const hash = new Bun.CryptoHasher("sha256").update(await Bun.file(jar).arrayBuffer()).digest("hex");
await Bun.write("src/android/pattern-data.ts", `// Generated by bun scripts/gen-patterns.ts from ${jar}.\n// SHA-256: ${hash}\nexport const PATTERNS = ${JSON.stringify(patterns, null, 2)};\n`);
